package com.deepcoder.hbalum.datalayers.model;


public class Account {

    private String title;
    private String description;
    private String careData;
    private String askContinueData;
    private String learnMore;
    private String urlPp;

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getCareData() {
        return careData;
    }

    public void setCareData(String careData) {
        this.careData = careData;
    }

    public String getAskContinueData() {
        return askContinueData;
    }

    public void setAskContinueData(String askContinueData) {
        this.askContinueData = askContinueData;
    }

    public String getLearnMore() {
        return learnMore;
    }

    public void setLearnMore(String learnMore) {
        this.learnMore = learnMore;
    }

    public String getUrlPp() {
        return urlPp;
    }

    public void setUrlPp(String urlPp) {
        this.urlPp = urlPp;
    }

}
